# Build the WebView2 host (with icon/version resources) and the developer engine driver.
#
#   powershell -ExecutionPolicy Bypass -File scripts/build-host.ps1
#
# The engine DLL (allinone.dll) is built separately:
#   powershell -ExecutionPolicy Bypass -File scripts/build-engine.ps1
$ErrorActionPreference = 'Stop'

$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$gpp = 'C:\msys64\ucrt64\bin\g++.exe'
$windres = 'C:\msys64\ucrt64\bin\windres.exe'
$sdk = Join-Path $root 'native\host\third_party\webview2'
$hostSrc = Join-Path $root 'native\host'
$hostBuild = Join-Path $root 'native\host\build'
$engineBuild = Join-Path $root 'native\build-engine'

if (-not (Test-Path $gpp)) { throw "g++ not found at $gpp" }
if (-not (Test-Path (Join-Path $sdk 'include\WebView2.h'))) { throw 'WebView2 SDK missing (see native/host/third_party/webview2/VERSION.txt)' }
New-Item -ItemType Directory -Force -Path $hostBuild, $engineBuild | Out-Null

# Version resource, generated from package.json.
$version = (Get-Content (Join-Path $root 'package.json') -Raw | ConvertFrom-Json).version
$parts = @($version.Split('.')) + @('0', '0', '0')
$comma = "$($parts[0]), $($parts[1]), $($parts[2]), 0"
@"
#pragma once
// Generated by scripts/build-host.ps1 from package.json.
#define AIO_VERSION_STRING "$version"
#define AIO_VERSION_COMMA $comma
"@ | Set-Content (Join-Path $hostSrc 'version.h') -Encoding ascii

Write-Host "building resources (version $version)"
& $windres -I $hostSrc -o (Join-Path $hostBuild 'host_res.o') (Join-Path $hostSrc 'host.rc')
if ($LASTEXITCODE -ne 0) { throw 'windres failed' }

Write-Host 'building aio-host.exe'
& $gpp -std=c++20 -O2 -DUNICODE -D_UNICODE -DNOMINMAX -D_WIN32_WINNT=0x0A00 `
    -I (Join-Path $sdk 'include') -I $hostSrc -I (Join-Path $root 'native') `
    -o (Join-Path $hostBuild 'aio-host.exe') `
    (Join-Path $hostSrc 'main.cpp') (Join-Path $root 'native\engine_server.cpp') (Join-Path $hostBuild 'host_res.o') `
    -lole32 -loleaut32 -lshell32 -luser32 -lgdi32 -lcomdlg32 -ladvapi32 -ldwmapi `
    -mwindows -static -static-libgcc -static-libstdc++
if ($LASTEXITCODE -ne 0) { throw 'aio-host build failed' }

Write-Host 'building aio-engine.exe (developer tool, not shipped)'
& $gpp -std=c++20 -O2 -DUNICODE -D_UNICODE -D_WIN32_WINNT=0x0A00 `
    -I (Join-Path $root 'native') `
    -o (Join-Path $root 'native\build-engine\aio-engine.exe') `
    (Join-Path $root 'native\engine_main.cpp') (Join-Path $root 'native\engine_server.cpp') `
    -static -static-libgcc -static-libstdc++
if ($LASTEXITCODE -ne 0) { throw 'aio-engine build failed' }

Copy-Item (Join-Path $sdk 'x64\WebView2Loader.dll') (Join-Path $hostBuild 'WebView2Loader.dll') -Force
New-Item -ItemType Directory -Force -Path (Join-Path $hostBuild 'web') | Out-Null
Copy-Item (Join-Path $hostSrc 'web\bridge.js') (Join-Path $hostBuild 'web\bridge.js') -Force

Get-ChildItem $hostBuild -Filter 'aio-host.exe' | Select-Object Name, @{n = 'KB'; e = { [math]::Round($_.Length / 1KB) } }
Get-ChildItem $engineBuild -Filter 'aio-engine.exe' | Select-Object Name, @{n = 'KB'; e = { [math]::Round($_.Length / 1KB) } }
Write-Host 'host build OK'



